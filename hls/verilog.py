"""Write hls_core.v (F, G, H) and its testbench.v (J) for a design."""
from .datapath import SLOT_BITS, SLOTS

MODULE = {"add": "adder", "sub": "subtractor", "mul": "multiplier"}
CODES = 64


def _v(src):
    """A mux source in Verilog: a register name or a 16-bit constant."""
    return f"16'd{src}" if isinstance(src, int) else src


def _sel_width(n):
    return max(1, (n - 1).bit_length())


def _lines(items, indent, width=100):
    """Pack 'stmt;' items into lines no wider than width."""
    out, line = [], ""
    for item in items:
        if line and len(indent) + len(line) + 1 + len(item) > width:
            out.append(indent + line)
            line = item
        else:
            line = f"{line} {item}" if line else item
    if line:
        out.append(indent + line)
    return out


def _decl(kind, names, indent="    "):
    """A declaration list, continued under its first name when it wraps."""
    first = indent + kind + " "
    lines = _lines([n + "," for n in names[:-1]] + [names[-1] + ";"], " " * len(first))
    lines[0] = first + lines[0].lstrip()
    return lines


def _steps(design, i):
    first, last = design.steps[i], design.last(i)
    return f"step {first}" if first == last else f"steps {first}-{last}"


def _ports(design):
    """(unit, port letter, sources) for every unit input that needs a mux."""
    return [(u, p, srcs) for u in design.units for p, srcs in zip("ab", u.ports) if len(srcs) > 1]


def _slot_comment(design):
    used = [f"{x} = {SLOTS[n]}" for n, x in enumerate(design.slots)]
    unused = SLOTS[len(design.slots):]
    if not used:
        return "no switch inputs"
    return "input slots: " + ", ".join(used + [f"{s} unused" for s in unused])


def core_v(design, title):
    """hls_core.v: units, input muxes, one register per value, the FSM and the observe mux."""
    ops, L = design.dag.ops, design.latency
    done = L + 1
    regs = design.slots + [op.dst for op in ops]
    muxed = _ports(design)
    out = ["`timescale 1ns/1ps", f"// Generated by hls from {title}.", "// Each op, its steps and its unit:"]
    width = max(len(op.text()) for op in ops)
    for i, op in enumerate(ops):
        out.append(f"//   {op.text().ljust(width)}  {_steps(design, i)}, {design.units[design.unit_of[i]].name}")
    for x, v in design.fixed.items():
        out.append(f"//   {x} = {v} (--set)")
    states = "1 = the step, 2 = DONE" if L == 1 else f"1-{L} = steps, {done} = DONE"
    unused_sw = len(design.slots) < len(SLOTS)
    out += ["module hls_core (",
            "    input             clk,",
            "    input             rst,",
            "    input             step,"]
    if unused_sw:
        out.append("    /* verilator lint_off UNUSED */")
    out.append(f"    input      [11:0] sw,      // {_slot_comment(design)}")
    if unused_sw:
        out.append("    /* verilator lint_on UNUSED */")
    out += ["    input      [5:0]  code,    // observe code",
            "    output reg [15:0] value,",
            "    output reg        valid,   // 0 = show ----",
            f"    output reg [7:0]  state,   // 0 = IDLE, {states}",
            "    output            done",
            ");",
            f"    localparam DONE = 8'd{done};",
            ""]
    out += _decl("reg [15:0]", regs)
    out += ["", "    // FSM outputs."]
    for w in sorted({_sel_width(len(s)) for _, _, s in muxed}):
        out += _decl("reg" if w == 1 else f"reg [{w - 1}:0]", [f"{u.name}_sel_{p}" for u, p, s in muxed
                                                               if _sel_width(len(s)) == w])
    out += _decl("reg", [f"{u.name}_busy" for u in design.units])
    out += _decl("reg", [f"{op.dst}_we" for op in ops])
    out += ["", "    // Units and their input muxes."]
    if muxed:
        out += _decl("reg  [15:0]", [f"{u.name}_{p}" for u, p, _ in muxed])
    out += _decl("wire [15:0]", [f"{u.name}_y" for u in design.units])
    out.append("")
    pins = [[f"{u.name}_{p}" if len(s) > 1 else _v(s[0]) for p, s in zip("ab", u.ports)] for u in design.units]
    wa = max(len(a) for a, _ in pins)
    wb = max(len(b) for _, b in pins)
    wm = max(len(MODULE[u.kind]) for u in design.units)
    for u, (a, b) in zip(design.units, pins):
        out.append(f"    {MODULE[u.kind].ljust(wm)} {u.name} (.a({a}),{' ' * (wa - len(a))} "
                   f".b({b}),{' ' * (wb - len(b))} .y({u.name}_y));")
    if muxed:
        out += ["", "    always @* begin"]
        for u, p, srcs in muxed:
            w = _sel_width(len(srcs))
            out.append(f"        case ({u.name}_sel_{p})")
            for n, src in enumerate(srcs[:-1]):
                label = f"{w}'d{n}:"
                out.append(f"            {label.ljust(8)} {u.name}_{p} = {_v(src)};")
            out.append(f"            default: {u.name}_{p} = {_v(srcs[-1])};")
            out.append("        endcase")
        out.append("    end")
    out += ["",
            "    // Sequencer: one state per step pulse, stopping at DONE.",
            "    always @(posedge clk)",
            "        if (rst) state <= 8'd0;",
            "        else if (step && state != DONE) state <= state + 8'd1;",
            "",
            "    assign done = (state == DONE);",
            "",
            "    // Moore outputs: each step's mux selects, busy units and register writes.",
            "    always @* begin"]
    defaults = [f"{u.name}_sel_{p} = {_sel_width(len(s))}'d0;" for u, p, s in muxed]
    defaults += [f"{u.name}_busy = 1'b0;" for u in design.units]
    defaults += [f"{op.dst}_we = 1'b0;" for op in ops]
    out += _lines(defaults, " " * 8)
    out.append("        case (state)")
    for t in range(1, L + 1):
        items = []
        for u, i in sorted(design.running(t)):
            unit = design.units[u]
            op = ops[i]
            for p, srcs, x in zip("ab", unit.ports, (op.a, op.b)):
                if len(srcs) > 1:
                    items.append(f"{unit.name}_sel_{p} = {_sel_width(len(srcs))}'d{srcs.index(design.source(x))};")
            items.append(f"{unit.name}_busy = 1'b1;")
        items += [f"{op.dst}_we = 1'b1;" for i, op in enumerate(ops) if design.last(i) == t]
        if items:
            out.append(f"            8'd{t}: begin")
            out += _lines(items, " " * 16)
            out.append("            end")
    out += ["            default: ;",
            "        endcase",
            "    end",
            "",
            "    // Inputs follow the switches in IDLE; results are written on the step pulse that ends their step.",
            "    always @(posedge clk)",
            "        if (rst) begin"]
    out += _lines([f"{x} <= 16'd0;" for x in regs], " " * 12)
    out.append("        end else begin")
    if design.slots:
        out.append("            if (state == 8'd0) begin")
        for n, x in enumerate(design.slots):
            out.append(f"                {x} <= {{12'd0, {SLOT_BITS[n]}}};")
        out.append("            end")
    for i, op in enumerate(ops):
        out.append(f"            if (step && {op.dst}_we) {op.dst} <= {design.units[design.unit_of[i]].name}_y;")
    out += ["        end",
            "",
            "    // Observe codes: units, then results in equation order, then inputs.",
            "    always @* begin",
            "        value = 16'd0; valid = 1'b0;",
            "        case (code)"]
    for n, (kind, name) in enumerate(design.codes):
        if kind == "unit":
            body = f"value = {name}_y; valid = {name}_busy;"
        elif kind == "result":
            body = f"value = {name}; valid = state > 8'd{design.last(_index(design, name))};"
        else:
            body = f"value = {name}; valid = 1'b1;"
        out.append(f"            6'd{n}: begin {body} end")
    out += ["            default: ;",
            "        endcase",
            "    end",
            "endmodule"]
    return "\n".join(out) + "\n"


def _index(design, dst):
    return next(i for i, op in enumerate(design.dag.ops) if op.dst == dst)


def testbench_v(design):
    """testbench.v: every switch setting against the SSA equations written out directly (J)."""
    ops, L = design.dag.ops, design.latency
    done = L + 1
    regs = list(design.program.inputs) + [op.dst for op in ops]
    sym = {"add": "+", "sub": "-", "mul": "*"}
    out = ["// Checks hls_core for every switch setting against the equations written out directly.",
           "`timescale 1ns/1ps",
           "module testbench;",
           "    reg         clk = 1'b0, rst = 1'b1, step = 1'b0;",
           "    reg  [11:0] sw = 12'd0;",
           "    reg  [5:0]  code = 6'd0;",
           "    wire [15:0] value;",
           "    wire        valid, done;",
           "    wire [7:0]  state;",
           "",
           "    hls_core dut (.clk(clk), .rst(rst), .step(step), .sw(sw), .code(code),",
           "                  .value(value), .valid(valid), .state(state), .done(done));",
           "",
           "    always #5 clk = ~clk;",
           "",
           "    // Reference: the SSA equations, 16 bits wide, with no schedule involved."]
    out += _decl("reg [15:0]", regs)
    out += ["    task reference;", "        begin"]
    for x in design.program.inputs:
        if x in design.fixed:
            out.append(f"            {x} = 16'd{design.fixed[x]};  // --set")
        else:
            out.append(f"            {x} = {SLOT_BITS[design.slots.index(x)]};")
    for op in ops:
        a, b = (f"16'd{x}" if isinstance(x, int) else x for x in (op.a, op.b))
        out.append(f"            {op.dst} = {a} {sym[op.kind]} {b};")
    out += ["        end",
            "    endtask",
            "",
            "    // What each observe code must show at DONE: idle units and unused codes show ----.",
            "    reg [15:0] want_value;",
            "    reg        want_valid;",
            "    task expected(input [5:0] c);",
            "        begin",
            "            want_valid = 1'b1;",
            "            want_value = 16'd0;",
            "            case (c)"]
    for n, (kind, name) in enumerate(design.codes):
        if kind != "unit":
            out.append(f"                6'd{n}: want_value = {name};")
    out += ["                default: want_valid = 1'b0;",
            "            endcase",
            "        end",
            "    endtask",
            "",
            "    task press;",
            "        begin",
            "            @(negedge clk) step = 1'b1;",
            "            @(negedge clk) step = 1'b0;",
            "        end",
            "    endtask",
            "",
            "    integer    errors = 0, passed = 0;",
            "    reg        bad;",
            "    reg [12:0] i;",
            "    reg [6:0]  c;",
            "",
            "    initial begin",
            "        for (i = 0; i < 4096; i = i + 1) begin",
            "            bad = 1'b0;",
            "            @(negedge clk) begin rst = 1'b1; sw = i[11:0]; end",
            "            @(negedge clk) rst = 1'b0;",
            "            reference;",
            "            press;                  // leave IDLE: the inputs freeze",
            "            sw = ~i[11:0];          // later switch changes must be ignored",
            f"            repeat ({L - 1}) press;{' ' * max(1, 8 - len(str(L - 1)))}// now in the last step, {L}",
            "            #1 if (done !== 1'b0) begin",
            "                bad = 1'b1;",
            "                if (errors < 5) $display(\"FAIL sw=%h: done is high before the last press\", i[11:0]);",
            "                errors = errors + 1;",
            "            end",
            "            press;                  // DONE",
            f"            #1 if (done !== 1'b1 || state !== 8'd{done}) begin",
            "                bad = 1'b1;",
            f"                if (errors < 5) $display(\"FAIL sw=%h: not DONE after {done} presses (state %h)\", "
            "i[11:0], state);",
            "                errors = errors + 1;",
            "            end",
            f"            for (c = 0; c < {CODES}; c = c + 1) begin",
            "                code = c[5:0];",
            "                expected(c[5:0]);",
            "                #1 if (valid !== want_valid || (want_valid && value !== want_value)) begin",
            "                    bad = 1'b1;",
            "                    if (errors < 5) $display(\"FAIL sw=%h code=%h: got %h valid=%b, expected %h valid=%b\",",
            "                                             i[11:0], c[5:0], value, valid, want_value, want_valid);",
            "                    errors = errors + 1;",
            "                end",
            "            end",
            "            if (!bad) passed = passed + 1;",
            "        end",
            "        if (passed == 4096) $display(\"PASS %0d/4096\", passed);",
            "        else $display(\"FAIL %0d/4096 passed\", passed);",
            "        $finish;",
            "    end",
            "endmodule"]
    return "\n".join(out) + "\n"
